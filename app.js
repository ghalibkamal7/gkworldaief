async function submitUsername(){
  const errEl = document.getElementById("usernameError");
  errEl.textContent = "";
  const raw = document.getElementById("usernameInput").value.trim();
  const clean = raw.toLowerCase().replace(/[^a-z0-9_]/g,"");
  if(clean.length < 3 || clean.length > 20 || clean !== raw.toLowerCase()){
    errEl.textContent = state.lang==="hi" ? "यूज़रनेम 3-20 अक्षरों का हो, सिर्फ़ अक्षर/अंक/underscore." : "Username must be 3-20 characters — letters, numbers, underscore only.";
    return;
  }
  if(!firebaseReady || !state.user){ errEl.textContent = t("auth.notConfigured"); return; }
  try{
    const existing = await db.collection("usernames").doc(clean).get();
    if(existing.exists){
      errEl.textContent = state.lang==="hi" ? "यह यूज़रनेम पहले से लिया जा चुका है — कोई और आज़माइए।" : "That username is already taken — try another.";
      return;
    }
    await db.collection("usernames").doc(clean).set({ uid: state.user.uid, displayUsername: raw, createdAt: firebase.firestore.FieldValue.serverTimestamp() });
    await db.collection("users").doc(state.user.uid).set({ username: raw, usernameLower: clean }, {merge:true});
    state.username = raw;
    showToast("toast.usernameSet");
    renderProfile(); renderAuthUI();
    resumePendingOrGoHome();
  }catch(e){
    console.error("[FIREBASE] username save error:", e);
    errEl.textContent = state.lang==="hi" ? "यह यूज़रनेम शायद पहले से लिया जा चुका है, या कुछ गड़बड़ हुई।" : "That username may already be taken, or something went wrong.";
  }
}

