// BADGES — evaluation engine (Part 2). Weekly/Monthly/Yearly winner badges are handled
// separately by checkPeriodWinnerBadges() since they need to compare against other users.
// ================================================================
function checkAndAwardBadges(opts){
  opts = opts || {};
  const awarded = [];
  BADGES.filter(b=>b.active).forEach(b=>{
    if(b.conditionType==="weeklyWins" || b.conditionType==="monthlyWins" || b.conditionType==="yearlyWins") return;
    const already = state.badgeCounts[b.id] || 0;
    let currentValue = 0;
    switch(b.conditionType){
      case "quizzesCompleted": currentValue = state.quizzesPlayed; break;
      case "questionsAttempted": currentValue = state.questionsAttempted; break;
      case "streak": currentValue = state.streak; break;
      case "fastAnswers": currentValue = state.fastAnswers; break;
      case "accuracyThreshold": currentValue = state.quizHistory.length ? Math.round(state.quizHistory.reduce((s,h)=>s+h.accuracy,0)/state.quizHistory.length) : 0; break;
      case "perfectScoreEvent": currentValue = state.perfectScores; break;
      case "sectionsParticipated": currentValue = state.sectionsParticipated.length; break;
      default: currentValue = 0;
    }
    if(currentValue < b.threshold) return;
    if(b.repeatable){
      if(b.conditionType==="perfectScoreEvent" && opts.perfectThisQuiz){
        state.badgeCounts[b.id] = already+1;
        state.badgeHistory.unshift({badgeId:b.id, dateEn:"Today", dateHi:"आज", timestamp:Date.now()});
        awarded.push(b);
      }
    } else if(already===0){
      state.badgeCounts[b.id] = 1;
      state.badgeHistory.unshift({badgeId:b.id, dateEn:"Today", dateHi:"आज", timestamp:Date.now()});
      awarded.push(b);
    }
  });
  return awarded;
}
// Best-effort Weekly/Monthly/Yearly Winner + Champion awarding. Without a server-side
// scheduler (no Cloud Functions on the Spark plan), no single moment exists where "the period
// just ended" can be evaluated for everyone at once — so instead, whenever ANY signed-in user
// opens the Leaderboard, their own client checks whether THEY currently sit at the top of that
// period's point standings and self-awards accordingly. This is disclosed as approximate: it
// resolves the next time the winner (or anyone) checks the leaderboard, not the instant the
// period closes, and ties are honoured (everyone sharing the top score is awarded).
async function checkPeriodWinnerBadges(){
  if(!firebaseReady || !state.user) return;
  const periods = [
    {field:"pointsWeek", badgeId:"weekly_winner"},
    {field:"pointsMonth", badgeId:"monthly_winner"},
    {field:"pointsYear", badgeId:"yearly_topper"}
  ];
  let changed = false;
  for(const p of periods){
    try{
      const snap = await db.collection("users").orderBy(p.field, "desc").limit(5).get();
      const rows = []; snap.forEach(d=> rows.push({uid:d.id, val:d.data()[p.field]||0}));
      if(rows.length===0 || rows[0].val<=0) continue;
      const topVal = rows[0].val;
      const amWinner = rows.some(r=> r.uid===state.user.uid && r.val===topVal);
      if(amWinner){
        const badge = BADGES.find(b=>b.id===p.badgeId);
        if(badge && badge.active){
          state.badgeCounts[badge.id] = (state.badgeCounts[badge.id]||0) + 1;
          state.badgeHistory.unshift({badgeId:badge.id, dateEn:"Today", dateHi:"आज", timestamp:Date.now()});
          showAchievementNotification(badge);
          changed = true;
          if(p.badgeId==="weekly_winner"){
            const champ = BADGES.find(b=>b.id==="champion");
            if(champ && champ.active){ state.badgeCounts[champ.id] = (state.badgeCounts[champ.id]||0)+1; }
          }
        }
      }
    }catch(e){ console.error("[FIREBASE] period winner check error:", e); }
  }
  if(changed){ saveUserData(); renderProfile(); }
}
