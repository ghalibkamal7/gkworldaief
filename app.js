async function loadRealLeaderboard(tab){
  if(!firebaseReady) return null;
  try{
    const field = LB_FIELD[tab];
    const snap = await db.collection("users").orderBy(field,"desc").limit(20).get();
    const rows = [];
    snap.forEach(d=>{
      const u = d.data();
      rows.push({ name: u.username ? "@"+u.username : (u.displayName || u.email || "Aspirant"), photoURL:u.photoURL||"", xp: u[field]||0, uid:d.id, me: state.user && d.id===state.user.uid });
    });
    console.log("[FIREBASE] Leaderboard ("+tab+") loaded:", rows.length, "users");
    return rows;
  }catch(e){ console.error("[FIREBASE] leaderboard load error:", e); return null; }
}
