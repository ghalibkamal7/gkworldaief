// AI HELPER — chat UI shell. Renders and accepts input regardless of configuration, but
// only actually calls a model when AI_HELPER_CONFIG.enabled is true; otherwise it explains
// why and stops there. No responses are ever simulated or hard-coded to look AI-generated.
// ================================================================
function renderAiHelperScreen(){
  const note = document.getElementById("aiNotConfiguredNote");
  const input = document.getElementById("aiInput");
  const sendBtn = document.getElementById("aiSendBtn");
  if(AI_HELPER_CONFIG.enabled){
    note.style.display = "none";
    input.disabled = false; sendBtn.disabled = false;
  } else {
    note.style.display = "block";
    note.textContent = t("ai.notConfigured");
    input.disabled = true; sendBtn.disabled = true;
  }
  if(aiChatHistory.length===0){
    aiChatHistory.push({role:"assistant", content: t("ai.welcome")});
  }
  renderAiMessages();
}
function renderAiMessages(){
  const wrap = document.getElementById("aiMessages");
  wrap.innerHTML = aiChatHistory.map(m=>{
    const isUser = m.role==="user";
    return `<div style="align-self:${isUser?'flex-end':'flex-start'};max-width:82%;background:${isUser?'var(--primary)':'var(--card)'};color:${isUser?'#fff':'var(--ink)'};border:${isUser?'none':'1px solid var(--line)'};border-radius:14px;padding:10px 13px;font-size:13.5px;line-height:1.5;box-shadow:var(--shadow)">${m.content}</div>`;
  }).join("");
  wrap.scrollTop = wrap.scrollHeight;
}
async function aiSendMessage(){
  const input = document.getElementById("aiInput");
  const text = input.value.trim();

  if(!text) return;

  if(!AI_HELPER_CONFIG.enabled){
    showToast("ai.notReadyToast");
    return;
  }

  // Add user's message to the local chat
  aiChatHistory.push({
    role: "user",
    content: text
  });

  input.value = "";
  renderAiMessages();

  try {
    const res = await fetch(AI_HELPER_CONFIG.endpoint, {
      method: "POST",
      headers: {
        "Content-Type": "application/json"
      },
      body: JSON.stringify({
        message: text,

        // Send previous conversation for context,
        // excluding the current message because it is sent separately.
        history: aiChatHistory
          .slice(0, -1)
          .filter(m =>
            m &&
            (m.role === "user" || m.role === "assistant") &&
            typeof m.content === "string"
          )
          .map(m => ({
            role: m.role === "assistant" ? "model" : "user",
            content: m.content
          })),

        systemInstruction:
          "You are a careful, encouraging study helper for Indian competitive-exam and school students, on the AIEF Quiz app. Explain doubts step by step in whichever of English, Hindi, or Hinglish the student used. Double-check any calculation before giving it. If you are not confident of a fact, say so plainly instead of guessing."
      })
    });

    const data = await res.json();

    if(!res.ok){
      throw new Error(
        data?.error || "AI Helper request failed."
      );
    }

    const reply =
      typeof data?.answer === "string" && data.answer.trim()
        ? data.answer.trim()
        : "Sorry, I couldn't get a response just now.";

    aiChatHistory.push({
      role: "assistant",
      content: reply
    });

  } catch(e) {
    console.error("[AI HELPER] request failed:", e);

    aiChatHistory.push({
      role: "assistant",
      content:
        state.lang === "hi"
          ? "माफ़ कीजिए, अभी जवाब नहीं मिल पाया।"
          : "Sorry, I couldn't get a response just now."
    });
  }

  renderAiMessages();
}
