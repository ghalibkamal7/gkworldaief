function renderAfCascade(){
  const wrap = document.getElementById("afCascadeWrap");
  if(!wrap) return;
  let html = "";
  let depth = 0;
  while(true){
    const parentId = depth===0 ? null : afPath[depth-1];
    const kids = depth===0 ? rootsOf(afSection) : childrenOf(parentId);
    if(kids.length===0) break; // nothing deeper here — the "attach here" button below covers this spot
    const currentVal = afPath[depth] || "";
    const levelLabel = kids[0].level ? (LEVEL_LABEL_KEY[kids[0].level] ? t(LEVEL_LABEL_KEY[kids[0].level]) : kids[0].level) : ((state.lang==="hi"?"स्तर ":"Level ")+(depth+1));
    html += `<div class="form-field"><label>${levelLabel}</label><select onchange="onAfCascadeChange(${depth}, this.value)">
      <option value="">${state.lang==="hi"?"चुनें":"Select"}…</option>
      ${kids.map(k=>`<option value="${k.id}" ${k.id===currentVal?"selected":""}>${state.lang==="hi"?k.nameHi:k.nameEn}</option>`).join("")}
    </select></div>`;
    if(!afPath[depth]) break; // stop until this level is actually picked
    depth++;
  }
  if(html===""){
    html = `<div class="empty-note">${state.lang==="hi" ? "यहाँ अभी कुछ नहीं है — पहले 'Content Tree' टैब से एक श्रेणी जोड़ें।" : "Nothing here yet — add a category from the Content Tree tab first."}</div>`;
  }
  const targetId = afPath.length ? afPath[afPath.length-1] : null;
  const targetNode = targetId ? nodeById(targetId) : null;
  if(targetNode){
    html += `<div class="empty-note" style="border-color:var(--success);color:var(--success);text-align:left">✓ ${state.lang==="hi"?"प्रश्न यहाँ जुड़ेगा:":"This question will attach to:"} <b>${pathLabel(targetId, state.lang)}</b></div>`;
  }
  wrap.innerHTML = html;
}
