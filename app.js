let NODES = [];
let nodeIdSeq = 0;
function mkNode(section, level, parentId, nameEn, nameHi, icon, order){
  const id = section.slice(0,3) + "_" + level.slice(0,2) + "_" + (nodeIdSeq++);
  NODES.push({id, section, level, parentId, nameEn, nameHi: nameHi||nameEn, icon: icon||null, order: typeof order==="number"?order:0});
  return id;
}
function nodeById(id){ return NODES.find(n=>n.id===id); }
function childrenOf(parentId){ return NODES.filter(n=>n.parentId===parentId).sort((a,b)=>a.order-b.order); }
function rootsOf(section){ return NODES.filter(n=>n.section===section && n.parentId===null).sort((a,b)=>a.order-b.order); }
// Suggests a sensible next-level name for the first few known depths of each section (purely
// a helpful default for the admin's "Level name" field) — it never blocks going deeper. There
// is no hard-coded depth limit: a node can always get another child, at any depth, forever.
function suggestNextLevelName(section, level){
  const seq = LEVELS[section];
  const i = seq.indexOf(level);
  if(i>=0 && seq[i+1]) return seq[i+1];
  return "";
}
// A node counts as holding quizzable content once it has any question attached — this is no
// longer tied to a specific level name like "part", so questions can be attached at ANY depth.
function nodeHasQuestions(nodeId){ return (QUESTIONS[nodeId]||[]).length > 0; }
function pathLabel(nodeId, lang){
  const parts = [];
  let cur = nodeById(nodeId);
  while(cur){ parts.unshift(lang==="hi"?cur.nameHi:cur.nameEn); cur = cur.parentId ? nodeById(cur.parentId) : null; }
  return parts.join(" › ");
}
function sectionLabel(section, lang){
  const key = section==="mcqs"?"sec.mcqs.title":section==="board"?"sec.board.title":"sec.entrance.title";
  return t(key, lang);
}
// Only Mathematics questions get the longer 12s timer — everything else gets 6s. Walks up
// from the part to find its ancestor "subject" node (works for mcqs, board, and entrance,
// since "subject" sits at a different depth in each but is always present).
function isMathQuestion(partId){
  let cur = nodeById(partId);
  while(cur){
    if(cur.level==="subject" && cur.nameEn==="Mathematics") return true;
    cur = cur.parentId ? nodeById(cur.parentId) : null;
  }
  return false;
}

