function adminMoveNode(nodeId, dir){
  const node = nodeById(nodeId);
  const sibs = childrenOf(node.parentId);
  const idx = sibs.findIndex(s=>s.id===nodeId);
  const swapIdx = dir==="up" ? idx-1 : idx+1;
  if(swapIdx<0 || swapIdx>=sibs.length) return;
  const a = sibs[idx], b = sibs[swapIdx];
  const tmp = a.order; a.order = b.order; b.order = tmp;
  if(firebaseReady){
    db.collection("nodes").doc(a.id).update({order:a.order}).catch(e=> reportFirestoreError("reordering", e));
    db.collection("nodes").doc(b.id).update({order:b.order}).catch(e=> reportFirestoreError("reordering", e));
  }
  renderAdminTree(); renderBrowse();
}
