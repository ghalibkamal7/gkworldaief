// ================================================================
// ONE-TIME AUTO-SEED — writes the local content tree + migrated questions into
// Firestore the first time an admin is signed in and those collections are still
// empty. Without this, the "nodes" collection would stay empty forever (nothing
// ever wrote the local seed to it), so the very first node an admin added would
// make the live sync above replace NODES with just that one document — wiping
// the rest of the tree out of the app for everyone, including on next login.
// Firestore security rules only allow admins to write nodes/questions, so this
// deliberately only runs once we know the signed-in user is an admin.
// ================================================================
async function seedFirestoreIfEmpty(){
  if(!firebaseReady || !state.isAdmin) return;
  try{
    const nodesSnap = await db.collection("nodes").limit(1).get();
    if(nodesSnap.empty){
      console.log("[FIREBASE] 'nodes' collection is empty — seeding local content tree (" + NODES.length + " nodes)...");
      await seedNodesToFirestore();
      console.log("[FIREBASE] 'nodes' seed complete.");
    } else {
      console.log("[FIREBASE] 'nodes' already has data — skipping seed.");
    }
  }catch(e){ console.error("[FIREBASE] nodes seed check/write failed:", e); }

  try{
    const qSnap = await db.collection("questions").limit(1).get();
    if(qSnap.empty){
      console.log("[FIREBASE] 'questions' collection is empty — seeding local questions...");
      await seedQuestionsToFirestore();
      console.log("[FIREBASE] 'questions' seed complete.");
    } else {
      console.log("[FIREBASE] 'questions' already has data — skipping seed.");
    }
  }catch(e){ console.error("[FIREBASE] questions seed check/write failed:", e); }

  try{
    const caSnap = await db.collection("currentAffairs").limit(1).get();
    if(caSnap.empty){
      console.log("[FIREBASE] 'currentAffairs' collection is empty — seeding local items...");
      const batch = db.batch();
      CURRENT_AFFAIRS.forEach(it=>{
        const {id, ...data} = it;
        batch.set(db.collection("currentAffairs").doc(id), data);
      });
      await batch.commit();
      console.log("[FIREBASE] 'currentAffairs' seed complete.");
    } else {
      console.log("[FIREBASE] 'currentAffairs' already has data — skipping seed.");
    }
  }catch(e){ console.error("[FIREBASE] currentAffairs seed check/write failed:", e); }

  try{
    const bSnap = await db.collection("badges").limit(1).get();
    if(bSnap.empty){
      console.log("[FIREBASE] 'badges' collection is empty — seeding default badge definitions...");
      const batch = db.batch();
      BADGES.forEach(b=>{
        const {id, ...data} = b;
        batch.set(db.collection("badges").doc(id), data);
      });
      await batch.commit();
      console.log("[FIREBASE] 'badges' seed complete.");
    } else {
      console.log("[FIREBASE] 'badges' already has data — skipping seed.");
    }
  }catch(e){ console.error("[FIREBASE] badges seed check/write failed:", e); }
}
async function seedNodesToFirestore(){
  let batch = db.batch(), opCount = 0;
  for(const n of NODES){
    batch.set(db.collection("nodes").doc(n.id), {
      section:n.section, level:n.level, parentId:n.parentId, nameEn:n.nameEn, nameHi:n.nameHi,
      icon: n.icon || null, order: n.order
    });
    opCount++;
    if(opCount >= 400){ await batch.commit(); batch = db.batch(); opCount = 0; }
  }
  if(opCount > 0) await batch.commit();
}
async function seedQuestionsToFirestore(){
  let batch = db.batch(), opCount = 0;
  for(const partId of Object.keys(QUESTIONS)){
    if(partId === "daily") continue;
    for(const q of QUESTIONS[partId]){
      const ref = db.collection("questions").doc();
      batch.set(ref, {
        partId, qEn:q.q.en, qHi:q.q.hi, optsEn:q.opts.en, optsHi:q.opts.hi,
        correct:q.correct, exEn:q.explain.en, exHi:q.explain.hi, createdAt: Date.now()
      });
      opCount++;
      if(opCount >= 400){ await batch.commit(); batch = db.batch(); opCount = 0; }
    }
  }
  if(opCount > 0) await batch.commit();
}

