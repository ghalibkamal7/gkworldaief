const LITERATURE_SUBJECTS = ["Hindi","English","Urdu","Sanskrit","NLH"]; // excluded from Board/Entrance fallback picks
function todayIST(){
  return new Intl.DateTimeFormat("en-CA", { timeZone:"Asia/Kolkata", year:"numeric", month:"2-digit", day:"2-digit" }).format(new Date());
}
// ---- IST calendar helpers for streaks + Weekly/Monthly/Yearly leaderboard periods ----
function getISTParts(date){
  const parts = {};
  new Intl.DateTimeFormat("en-US", { timeZone:"Asia/Kolkata", year:"numeric", month:"2-digit", day:"2-digit" }).formatToParts(date).forEach(p=>{ parts[p.type]=p.value; });
  return parts;
}
function istCalendarDate(date){
  const p = getISTParts(date);
  return new Date(Date.UTC(parseInt(p.year), parseInt(p.month)-1, parseInt(p.day)));
}
function weekKeyIST(date){
  // Weekly period = Friday 00:00 → Thursday 23:59 IST. Key = that week's Friday date, so it's
  // stable and sortable, and changes exactly when a new week starts.
  const d = istCalendarDate(date);
  const day = d.getUTCDay(); // 0=Sun..6=Sat
  const diff = (day - 5 + 7) % 7;
  d.setUTCDate(d.getUTCDate() - diff);
  return d.toISOString().slice(0,10);
}
function monthKeyIST(date){ const p = getISTParts(date); return p.year+"-"+p.month; }
function yearKeyIST(date){ return getISTParts(date).year; }
function daysBetweenISTKeys(a, b){
  return Math.round((new Date(b+"T00:00:00Z") - new Date(a+"T00:00:00Z")) / 86400000);
}
// Called once per completed quiz — advances the daily streak and resets Weekly/Monthly/Yearly
// point counters the first time each new period is noticed (archiving the just-ended period's
// total into quizHistory-style records first, so nothing is silently lost on rollover).
function updateStreakAndPeriods(){
  const now = new Date();
  const todayKey = todayIST();
  if(state.lastActiveDateIST !== todayKey){
    if(state.lastActiveDateIST){
      const gap = daysBetweenISTKeys(state.lastActiveDateIST, todayKey);
      state.streak = gap===1 ? state.streak+1 : 1;
    } else {
      state.streak = 1;
    }
    state.lastActiveDateIST = todayKey;
    if(state.streak > state.longestStreak) state.longestStreak = state.streak;
  }
  const wk = weekKeyIST(now), mk = monthKeyIST(now), yk = yearKeyIST(now);
  if(state.periodKeys.week && state.periodKeys.week !== wk) state.pointsWeek = 0;
  if(state.periodKeys.month && state.periodKeys.month !== mk) state.pointsMonth = 0;
  if(state.periodKeys.year && state.periodKeys.year !== yk) state.pointsYear = 0;
  state.periodKeys = {week:wk, month:mk, year:yk};
}
function bookmarkKeyOf(it){ return it.partId+"::"+it.qIndex; }
function subjectNameOf(partId){
  let cur = nodeById(partId);
  while(cur){ if(cur.level==="subject") return cur.nameEn; cur = cur.parentId ? nodeById(cur.parentId) : null; }
  return "";
}
function buildMcqsPool(){
  const pool = [];
  NODES.filter(n=>n.section==="mcqs" && n.level==="part").forEach(p=>{
    (QUESTIONS[p.id]||[]).forEach((q,i)=> pool.push({partId:p.id, qIndex:i}));
  });
  return pool;
}
function buildBoardEntrancePool(){
  const pool = [];
  NODES.filter(n=>(n.section==="board"||n.section==="entrance") && n.level==="part").forEach(p=>{
    if(LITERATURE_SUBJECTS.includes(subjectNameOf(p.id))) return; // avoid literature/story-based subjects by default
    (QUESTIONS[p.id]||[]).forEach((q,i)=> pool.push({partId:p.id, qIndex:i}));
  });
  return pool;
}
function shuffleArr(arr){
  for(let i=arr.length-1;i>0;i--){ const j=Math.floor(Math.random()*(i+1)); [arr[i],arr[j]]=[arr[j],arr[i]]; }
  return arr;
}
async function getRecentlyUsedKeys(days){
  const keys = new Set();
  if(!firebaseReady) return keys;
  try{
    const snap = await db.collection("dailyChallenges").orderBy(firebase.firestore.FieldPath.documentId(), "desc").limit(days).get();
    snap.forEach(d=>{ (d.data().items||[]).forEach(it=> keys.add(bookmarkKeyOf(it))); });
  }catch(e){ console.error("[FIREBASE] getRecentlyUsedKeys error:", e); }
  return keys;
}
function pickFrom(pool, n, avoidSet, alreadyPicked){
  let fresh = pool.filter(it=> !avoidSet.has(bookmarkKeyOf(it)) && !alreadyPicked.has(bookmarkKeyOf(it)));
  if(fresh.length < n){
    // Not enough unseen-recently questions — allow repeats from the avoid window rather
    // than duplicate within the same challenge (never violates the no-duplicate rule).
    fresh = pool.filter(it=> !alreadyPicked.has(bookmarkKeyOf(it)));
  }
  return shuffleArr(fresh).slice(0, Math.min(n, fresh.length));
}
async function generateDailyChallenge(dateStr){
  const mcqsPool = buildMcqsPool();
  const bePool = buildBoardEntrancePool();
  const avoid = await getRecentlyUsedKeys(7); // avoid repeating anything from the last 7 days when possible
  const picked = new Set();

  let mcqsPicks = pickFrom(mcqsPool, 7, avoid, picked);
  mcqsPicks.forEach(it=> picked.add(bookmarkKeyOf(it)));
  let bePicks = pickFrom(bePool, 3, avoid, picked);
  bePicks.forEach(it=> picked.add(bookmarkKeyOf(it)));

  let allPicks = mcqsPicks.concat(bePicks);
  if(allPicks.length < 10){
    // Fallback: preferred 7+3 pattern wasn't fully available — top up from whichever pool
    // still has eligible questions left, without ever duplicating a question in this challenge.
    const need = 10 - allPicks.length;
    const topUpPool = mcqsPicks.length < 7 ? bePool : mcqsPool;
    const extra = pickFrom(topUpPool, need, avoid, picked);
    extra.forEach(it=> picked.add(bookmarkKeyOf(it)));
    allPicks = allPicks.concat(extra);
  }
  const warning = allPicks.length < 10;
  shuffleArr(allPicks); // mix MCQs/Board/Entrance questions together rather than blocks

  const items = allPicks.map(it=> ({ partId: it.partId, qIndex: it.qIndex, timerSec: isMathQuestion(it.partId) ? 12 : 6 }));
  const payload = { items, generatedAt: Date.now(), mcqsCount: mcqsPicks.length, boardEntranceCount: bePicks.length, warning };
  if(firebaseReady){
    try{ await db.collection("dailyChallenges").doc(dateStr).set(payload); console.log("[FIREBASE] Daily challenge generated for", dateStr, payload); }
    catch(e){ console.error("[FIREBASE] saving daily challenge failed:", e); }
  }
  return payload;
}
async function loadTodayChallenge(){
  const dateStr = todayIST();
  try{
    const doc = await db.collection("dailyChallenges").doc(dateStr).get();
    if(doc.exists) return doc.data();
    return await generateDailyChallenge(dateStr);
  }catch(e){ console.error("[FIREBASE] loadTodayChallenge error:", e); return null; }
}
